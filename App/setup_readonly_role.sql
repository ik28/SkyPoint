-- Read-only role for the plain-English app. Run once as ACCOUNTADMIN.
USE ROLE ACCOUNTADMIN;

CREATE ROLE IF NOT EXISTS SKYPOINTS_READER;

GRANT USAGE ON WAREHOUSE SNOWFLAKE_LEARNING_WH TO ROLE SKYPOINTS_READER;
GRANT USAGE ON DATABASE SKYPOINTS TO ROLE SKYPOINTS_READER;
GRANT USAGE ON SCHEMA SKYPOINTS.GOLD TO ROLE SKYPOINTS_READER;

-- Only the two views the app is allowed to query.
GRANT SELECT ON VIEW SKYPOINTS.GOLD.VW_MEMBER_HORIZON_SUMMARY TO ROLE SKYPOINTS_READER;
GRANT SELECT ON VIEW SKYPOINTS.GOLD.VW_REDEMPTIONS_ENRICHED TO ROLE SKYPOINTS_READER;

GRANT ROLE SKYPOINTS_READER TO USER AIRFLOW_USER;

